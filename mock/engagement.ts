export function buildEngagement(accountId: AccountId, photos: Photo[]): EngagementItem[] {
  const published = photos.filter((p) => p.status === "published");
  return seeds[accountId].map((s, i) => ({
    id: `${accountId}-e${i}`,
    kind: s.kind,
    customer: { name: s.name, handle: s.handle, tint: i % 6 },
    text: s.text,
    at: ago(0, s.hoursAgo),
    photoId: s.post !== undefined ? published[s.post]?.id : undefined,
    unread: Boolean(s.unread),
    aiReply: s.aiReply,
    alternatives: s.alternatives,
    sent: s.sent ? { text: s.sent.text ?? s.aiReply, as: s.sent.as, at: ago(0, s.sent.hoursAgo) } : undefined,
  }));
}
